// What each trait, way, stance and die-off is drawn with. A trait with no icon of its own takes its branch's.
const TRAIT_ICON = { jawFish: 'fish', jawInsects: 'insects', jawPlants: 'plants', jawPrey: 'prey', omni: 'food', scavenge: 'carrion', crush: 'hard', tongue: 'insects', scales: 'cover' };
const DIEOFF_ICON = { cold: 'cold', greatCold: 'cold', heat: 'heat', greatHot: 'heat', drought: 'drought', greatDry: 'drought', collapse: 'collapse', greatWaste: 'waste' };

const cache = new Map();
/** An icon as inline SVG, coloured by the text around it. Unknown names draw nothing. */
export function icon(name, cls = '') {
  const rows = ICONS[name];
  if (!rows) return '';
  const key = `${name}|${cls}`;
  if (cache.has(key)) return cache.get(key);
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < 8;) {
      const c = row[x];
      if (c === '.') { x++; continue; }
      let w = 1; while (x + w < 8 && row[x + w] === c) w++;
      rects += `<rect x="${x}" y="${y}" width="${w}" height="1"${c === '+' ? ' opacity=".45"' : ''}/>`;
      x += w;
    }
  });
  const svg = `<svg class="ic${cls ? ` ${cls}` : ''}" viewBox="0 0 8 8" fill="currentColor" shape-rendering="crispEdges" aria-hidden="true">${rects}</svg>`;
  cache.set(key, svg);
  return svg;
}

/** The icon for a trait: its own, or its branch's in the tree. */
export const traitIcon = (id, cls) => icon(TRAIT_ICON[id] || (ICONS[id] ? id : TREE.find((b) => b.traits.includes(id))?.id) || 'grow', cls);
export const dieoffIcon = (kind, cls) => icon(DIEOFF_ICON[kind] || 'waste', cls);
